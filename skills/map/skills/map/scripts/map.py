#!/usr/bin/env python3
"""Computed facts for the map skill: registers, duplicates, reuse candidates, and staleness.

Needs Python 3.9+ and git. Writes only inside map/, plus one .gitignore line on init.
"""

import argparse
import fnmatch
import hashlib
import json
import re
import subprocess
import sys
from collections import Counter, defaultdict, deque
from pathlib import Path

CODE = set(".js .jsx .ts .tsx .mjs .cjs .vue .svelte .astro .py .rb .go .rs .java .kt .swift .dart .cs .c .h .cc .cpp .php .ex .exs .scala .sh".split())
IMAGES = set(".png .jpg .jpeg .webp .avif .gif .svg .ico".split())
TEXT = CODE | set(".html .css .scss .md .mdx .json .yml .yaml .toml .xml .plist .storyboard .arb".split())
GENERATED = re.compile(r"(^|/)(vendor|node_modules|dist|build|Pods|Plugins|third_party|ThirdParty|external|AutoGeneratedCode|__generated__|generated|\.next|\.dart_tool)/|\.min\.|\.g\.dart$|\.freezed\.dart$|\.pb\.|\.d\.ts$")
TESTS = re.compile(r"(^|/)(tests?|__tests__|spec|e2e|fixtures?)/|[._-](test|spec)\.\w+$|(^|/)test_[^/]+$")
SYMBOL = re.compile(
    r"^export\s+(?:default\s+)?(?:async\s+)?(?:function\*?|const|class|let)\s+([A-Za-z_$][\w$]*)"
    r"|^export\s+default\s+([A-Za-z_$][\w$]*);?\s*$"
    r"|^(?:public\s+)?fun\s+([A-Za-z]\w*)"
    r"|^(?:async\s+)?def\s+([A-Za-z][\w]*)|^class\s+([A-Za-z]\w*)"
    r"|^func\s+(?:\([^)]*\)\s*)?([A-Z]\w*)"
    r"|^pub\s+(?:async\s+)?(?:fn|struct|enum|trait)\s+(\w+)"
    r"|^\s*public\s+(?:static\s+|sealed\s+|abstract\s+|partial\s+)*(?:class|struct|interface|enum)\s+(\w+)"
    r"|^(?:public\s+|open\s+|final\s+)*(?:struct|enum|protocol|actor)\s+(\w+)",
    re.M,
)
COMMON_NAMES = set("default index main app config props state options init setup render run handler get post put delete test helper utils types".split())
SKIP_LINE = re.compile(r"^(?://|#(?!include)|/?\*|--|import\b|from\s+\S+\s+import\b|using\b|package\b|#include\b|require\b|export\s*\{|[\s\W]*$)")
FILE_COMPONENTS = {".astro", ".vue", ".svelte"}
JS_FAMILY = {".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs", ".vue", ".svelte", ".astro"}
WINDOW, MAX_COPIES = 6, 12
PAGE_LIMIT, PAGE_AIM, NEEDS_CONTENTS, MAX_DEPTH, ROOT_AIM, IMAGE_KB, REGISTER_ROWS = 500, 200, 100, 3, 80, 400, 300
COVERS_SHARE = 0.5
STATE, IGNORE, IMAGES_PAGE, DUPES_PAGE = ".state.json", ".ignore", "images.md", "dupes.md"


def git(*args, check=True):
    done = subprocess.run(["git", *args], cwd=CWD, capture_output=True)
    if check and done.returncode:
        sys.exit(f"git {args[0]} failed: {done.stderr.decode(errors='replace').strip()}")
    return done.stdout.decode(errors="surrogateescape")


CWD = Path.cwd()


def locate():
    """The checkout root, and the map, which lives in the main checkout so worktrees share one."""
    root = git("rev-parse", "--show-toplevel", check=False).strip()
    if not root:
        sys.exit("map needs a git repository")
    common = (CWD / git("rev-parse", "--git-common-dir").strip()).resolve()
    return Path(root), common.parent / "map"


def blob_id(path):
    data = path.read_bytes()
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def tree(root, map_dir):
    """Every tracked or addable file with its content id, working tree included, minus map/.ignore."""
    files = {}
    for row in filter(None, git("ls-files", "-s", "-z").split("\0")):
        meta, path = row.split("\t", 1)
        mode, blob, _ = meta.split()
        if mode != "160000":
            files[path] = blob
    for path in filter(None, git("ls-files", "-d", "-z").split("\0")):
        files.pop(path, None)
    changed = git("ls-files", "-m", "-o", "--exclude-standard", "-z").split("\0")
    for path in filter(None, changed):
        if path == "map" or path.startswith("map/"):
            continue
        if (root / path).is_file():
            files[path] = blob_id(root / path)
    ignore = map_dir / IGNORE
    excluded = [glob_regex(line) for line in ignore.read_text().splitlines() if line.strip() and not line.startswith("#")] if ignore.exists() else []
    return {path: blob for path, blob in files.items() if not path.startswith("map/") and not any(rx.match(path) for rx in excluded)}


def suffix(path):
    return Path(path).suffix.lower()


def code_files(files):
    return [p for p in files if suffix(p) in CODE and not GENERATED.search(p)]


def read(root, path, limit=512_000):
    target = root / path
    if not target.is_file() or target.stat().st_size > limit:
        return ""
    return target.read_text(errors="replace")


def glob_regex(pattern):
    pattern = pattern.strip().rstrip("/")
    if not re.search(r"[*?\[]", pattern):
        return re.compile(re.escape(pattern) + r"(/.*)?$")
    parts = re.split(r"(\*\*/?)", pattern)
    body = "".join(".*" if part.startswith("**") else fnmatch.translate(part)[4:-3].replace(".*", "[^/]*") for part in parts)
    return re.compile(body + "$")


def header(text, label):
    for line in text.splitlines()[:6]:
        if line.startswith(label + ":"):
            return line[len(label) + 1 :].strip()
    return ""


def covers(text):
    return [item for item in re.split(r"[,\s]+", header(text, "Covers")) if item]


def pages(map_dir):
    return sorted(map_dir.rglob("*.md"))


def load_state(map_dir):
    path = map_dir / STATE
    return json.loads(path.read_text()) if path.exists() else {"pages": {}, "images": {}}


def save_state(map_dir, state):
    (map_dir / STATE).write_text(json.dumps(state, indent=0, sort_keys=True))


def covered(page_name, text, files):
    if page_name == IMAGES_PAGE:
        return {p: b for p, b in files.items() if suffix(p) in IMAGES}
    if page_name == DUPES_PAGE:
        return {p: files[p] for p in code_files(files)}
    patterns = [glob_regex(item) for item in covers(text)]
    return {p: b for p, b in files.items() if any(rx.match(p) for rx in patterns)}


def stale_pages(map_dir, files, state):
    """Pages whose covered files changed since they were last stamped: {page: [change, ...]}."""
    result = {}
    for page in pages(map_dir):
        name = page.relative_to(map_dir).as_posix()
        current = covered(name, page.read_text(), files)
        if not current and name not in (IMAGES_PAGE, DUPES_PAGE):
            continue
        stamped = state["pages"].get(name)
        if stamped is None:
            result[name] = ["never stamped"]
            continue
        changes = [f"{p} (changed)" for p in sorted(current) if p in stamped and stamped[p] != current[p]]
        changes += [f"{p} (added)" for p in sorted(current) if p not in stamped]
        changes += [f"{p} (removed)" for p in sorted(stamped) if p not in current]
        if changes:
            result[name] = changes
    return result


def table_cells(line):
    return [cell.strip().replace("\\|", "|") for cell in re.split(r"(?<!\\)\|", line.strip())[1:-1]]


def kept_column(path):
    """Row key -> last cell of a register, so regenerating never loses what a person or agent wrote."""
    if not path.exists():
        return {}
    kept = {}
    for line in path.read_text().splitlines():
        cells = table_cells(line) if line.startswith("|") else []
        if len(cells) >= 2 and cells[-1] and not set(cells[0]) <= set("-: "):
            kept[cells[0].strip("`")] = cells[-1]
    return kept


def cell(value):
    return str(value).replace("|", "\\|")


def cmd_init(root, map_dir, args):
    home = map_dir.parent
    if git("ls-files", "--", str(map_dir), check=False).strip():
        sys.exit("map/ holds tracked files. It is not this skill's folder, so nothing was changed.")
    if map_dir.exists() and any(map_dir.iterdir()) and not (map_dir / STATE).exists():
        sys.exit("map/ already exists and was not made by this skill, so nothing was changed.")
    (map_dir / "images").mkdir(parents=True, exist_ok=True)
    if not (map_dir / STATE).exists():
        save_state(map_dir, {"pages": {}, "images": {}})
    ignored = subprocess.run(["git", "check-ignore", "-q", "map/"], cwd=home).returncode == 0
    if not ignored:
        gitignore = home / ".gitignore"
        existing = gitignore.read_text() if gitignore.exists() else ""
        gitignore.write_text(existing + ("" if not existing or existing.endswith("\n") else "\n") + "/map/\n")
    print(f"map ready at {map_dir}" + ("" if ignored else " (added /map/ to .gitignore)"))


def cmd_scan(root, map_dir, args):
    """Where the code is, by area, so build effort goes where it is worth it."""
    files = tree(root, map_dir)
    code = code_files(files)
    areas = defaultdict(lambda: [0, 0])
    for path in code:
        parts = path.split("/")
        depth = 2 if parts[0] in ("src", "lib", "app", "packages", "apps", "Assets") and len(parts) > 2 else 1
        area = "/".join(parts[:depth]) if len(parts) > 1 else "(root)"
        areas[area][0] += 1
        areas[area][1] += read(root, path).count("\n")
    languages = Counter(suffix(p) for p in code).most_common(6)
    images = [p for p in files if suffix(p) in IMAGES]
    print(f"{len(files)} files, {len(code)} code, {len(images)} images. Languages: " + ", ".join(f"{k} {v}" for k, v in languages))
    for area, (count, lines) in sorted(areas.items(), key=lambda kv: -kv[1][1])[: args.limit]:
        print(f"{lines:>7} lines  {count:>4} files  {area}")
    if len(areas) > args.limit:
        print(f"(+{len(areas) - args.limit} smaller areas)")


def symbols_of(root, code):
    found = defaultdict(list)
    for path in code:
        for groups in SYMBOL.findall(read(root, path)):
            name = next(g for g in groups if g)
            found[name].append(path)
        if suffix(path) in FILE_COMPONENTS:
            found[Path(path).stem].append(path)
    return found


def cmd_symbols(root, map_dir, args):
    """Exported names ranked by how many other files mention them. Fan-in finds what is really shared."""
    code = [p for p in code_files(tree(root, map_dir)) if not TESTS.search(p)]
    found = symbols_of(root, code)
    family = lambda path: "js" if suffix(path) in JS_FAMILY else suffix(path)
    tokens = defaultdict(Counter)
    for path in code:
        tokens[family(path)].update(set(re.findall(r"[A-Za-z_$][\w$]*", read(root, path))))
    pattern = glob_regex(args.glob) if args.glob else None
    rows = []
    for name, paths in found.items():
        if name.lower() in COMMON_NAMES:
            continue
        for path in sorted(set(paths)):
            if not pattern or pattern.match(path):
                rows.append((max(tokens[family(path)][name] - 1, 0), name, path))
    rows.sort(key=lambda row: (-row[0], row[1]))
    print("fan-in  name  path")
    for fan_in, name, path in rows[: args.limit]:
        print(f"{fan_in:>6}  {name}  {path}")
    if len(rows) > args.limit:
        print(f"(+{len(rows) - args.limit} more; narrow with a glob)")


def meaningful_lines(text):
    rows = []
    for number, line in enumerate(text.splitlines(), 1):
        norm = " ".join(line.split())
        if not SKIP_LINE.match(norm):
            rows.append((number, norm))
    return rows


def repeated_blocks(root, code):
    """Maximal identical runs of meaningful lines, whitespace ignored. Renamed copies are not caught."""
    lines = {path: meaningful_lines(read(root, path)) for path in code}
    windows = defaultdict(list)
    for path, rows in lines.items():
        for i in range(len(rows) - WINDOW + 1):
            windows[hash(tuple(r[1] for r in rows[i : i + WINDOW]))].append((path, i))
    blocks = {}
    for spots in windows.values():
        if not 2 <= len(spots) <= MAX_COPIES:
            continue
        for x in range(len(spots)):
            for y in range(x + 1, len(spots)):
                (a, i), (b, j) = spots[x], spots[y]
                ra, rb = lines[a], lines[b]
                if a == b and j - i < WINDOW:
                    continue
                if i and j and ra[i - 1][1] == rb[j - 1][1]:
                    continue
                n = 0
                while i + n < len(ra) and j + n < len(rb) and ra[i + n][1] == rb[j + n][1] and (a != b or i + n < j):
                    n += 1
                if n < WINDOW:
                    continue
                text = "\n".join(r[1] for r in ra[i : i + n])
                key = "b-" + hashlib.sha1(text.encode()).hexdigest()[:7]
                block = blocks.setdefault(key, {"lines": n, "where": set()})
                block["where"].add((a, ra[i][0], ra[i + n - 1][0]))
                block["where"].add((b, rb[j][0], rb[j + n - 1][0]))
    return blocks


def block_families(blocks):
    """Overlapping runs are one copied thing seen at different lengths, so report them once."""
    keys = sorted(blocks, key=lambda k: (-blocks[k]["lines"], k))
    families = []
    for key in keys:
        where = set(blocks[key]["where"])
        for family in families:
            if any(a == x and s <= f and y <= e for a, s, e in where for x, y, f in family["where"]):
                family["where"] |= where
                break
        else:
            families.append({"key": key, "lines": blocks[key]["lines"], "where": where})
    return families


def duplicate_rows(root, files):
    code = code_files(files)
    rows = []
    for family in block_families(repeated_blocks(root, code)):
        best = {}
        for path, start, end in sorted(family["where"]):
            if path not in best or end - start > best[path][1] - best[path][0]:
                best[path] = (start, end)
        if all(TESTS.search(path) for path in best):
            continue
        spots = [f"`{p}:{s}-{e}`" for p, (s, e) in sorted(best.items())]
        copies = max(len(best), 2)
        rows.append((family["lines"] * (copies - 1), family["key"], "repeated code", f"{family['lines']}+ lines, {copies} places", spots))
    non_test = [p for p in code if not TESTS.search(p)]
    for name, paths in symbols_of(root, non_test).items():
        unique = sorted(set(paths))
        stems = {Path(p).parent.as_posix() + "/" + Path(p).name.split(".")[0] for p in unique}
        if len(unique) < 2 or len(stems) < 2 or len(name) < 4 or name.lower() in COMMON_NAMES:
            continue
        key = "s-" + hashlib.sha1(name.encode()).hexdigest()[:7]
        rows.append((len(unique) * 3, key, "same name", f"`{name}` x{len(unique)}", [f"`{p}`" for p in unique]))
    by_blob = defaultdict(list)
    for path in code:
        by_blob[files[path]].append(path)
    for blob, paths in by_blob.items():
        if len(paths) > 1 and (root / paths[0]).exists() and (root / paths[0]).stat().st_size >= 200:
            lines = read(root, paths[0]).count("\n")
            rows.append((lines * (len(paths) - 1), "f-" + blob[:7], "identical file", f"{lines} lines x{len(paths)}", [f"`{p}`" for p in sorted(paths)]))
    return sorted(rows, key=lambda row: (-row[0], row[1]))


def cmd_dupes(root, map_dir, args):
    files = tree(root, map_dir)
    rows = duplicate_rows(root, files)
    print(f"{len(rows)} duplicate groups")
    for score, key, kind, size, where in rows[:args.limit]:
        print(f"{key}  {kind}  {size}  " + " ".join(w.strip('`') for w in where[:4]) + (f" +{len(where) - 4}" if len(where) > 4 else ""))
    if not args.write:
        return
    target = map_dir / DUPES_PAGE
    decisions = kept_column(target)
    shown = rows[:REGISTER_ROWS // 3]
    out = [
        "# Duplicates",
        "",
        "Up: [Map](README.md)",
        "",
        f"Generated by map.py: {len(rows)} groups, largest first. Edit only the Decision column; it survives regeneration. "
        "Write `canonical: <path>` or `accepted: <why>`. Exact copies and same-named exports only: renamed copies are not caught, and a same-name row may be coincidence.",
        "",
        "| ID | Kind | Size | Where | Decision |",
        "| - | - | - | - | - |",
    ]
    for _, key, kind, size, where in shown:
        decision = decisions.get(key, "")
        out.append(f"| {key} | {kind} | {cell(size)} | {' '.join(where[:6])}{f' +{len(where) - 6}' if len(where) > 6 else ''} | {cell(decision)} |")
    if len(rows) > len(shown):
        out += ["", f"{len(rows) - len(shown)} smaller groups not listed."]
    target.write_text("\n".join(out) + "\n")
    stamp(map_dir, files, [DUPES_PAGE])
    print(f"wrote {target}")


def image_rows(root, map_dir, files):
    images = {p: b for p, b in files.items() if suffix(p) in IMAGES}
    mentions = defaultdict(set)
    for path in files:
        if suffix(path) in TEXT and not GENERATED.search(path):
            text = read(root, path)
            for name in set(re.findall(r"[\w@.+-]+\.(?:png|jpe?g|webp|avif|gif|svg|ico)\b", text, re.I)):
                mentions[name.lower()].add(path)
    rows = {}
    for path in images:
        target = root / path
        rows[path] = {"kb": target.stat().st_size // 1024 if target.exists() else 0, "used": sorted(mentions[Path(path).name.lower()] - {path})}
    return images, rows


def cmd_images(root, map_dir, args):
    files = tree(root, map_dir)
    images, rows = image_rows(root, map_dir, files)
    groups = defaultdict(list)
    for path, blob in images.items():
        groups[blob].append(path)
    copies = [sorted(paths) for paths in groups.values() if len(paths) > 1]
    copies.sort(key=lambda paths: -rows[paths[0]]["kb"] * (len(paths) - 1))
    unused = sorted(p for p in images if not rows[p]["used"])
    total = sum(r["kb"] for r in rows.values())
    print(f"{len(images)} images, {total} KB, {len(copies)} sets of exact copies, {len(unused)} with no text reference")
    if images and len(unused) > len(images) / 2:
        print("Most images have no text reference, so this repo loads them another way (GUIDs, computed names). That list means nothing here.")
        unused = []
    for paths in copies[:args.limit]:
        print("copies: " + " = ".join(paths[:4]) + (f" +{len(paths) - 4}" if len(paths) > 4 else ""))
    for path in unused[:args.limit]:
        print(f"no reference: {path}")
    if not args.write:
        return
    target = map_dir / IMAGES_PAGE
    state = load_state(map_dir)
    shows = kept_column(target)
    moved = {blob: shows[path] for path, blob in state.get("images", {}).items() if path in shows}
    stored = sorted(p.relative_to(map_dir).as_posix() for p in (map_dir / "images").rglob("*") if suffix(p.name) in IMAGES) if (map_dir / "images").exists() else []
    out = [
        "# Images",
        "",
        "Up: [Map](README.md)",
        "",
        f"Generated by map.py: {len(images)} images in the repo, {total} KB. Fill in only the Shows column; it survives regeneration and moves with the file. "
        "Read a row here before opening an image. Product assets stay where the build expects them; only reference images live in `map/images/`.",
        "",
    ]
    if copies:
        out += ["## Exact copies", ""] + ["- " + " = ".join(f"`{p}`" for p in paths[:6]) for paths in copies[:40]] + [""]
    if unused:
        out += ["## No text reference", "", "Candidates only: assets loaded by computed name, GUID or tool show up here too. Search before deleting.", ""]
        out += [f"- `{p}`" for p in unused[:40]]
        out += ([f"- (+{len(unused) - 40} more)"] if len(unused) > 40 else []) + [""]
    if stored:
        out += ["## Reference images (map/images/)", "", "| Image | Shows |", "| - | - |"]
        out += [f"| [{name}]({name}) | {cell(shows.get(name, ''))} |" for name in stored] + [""]
    listed = sorted(images)
    if len(listed) > REGISTER_ROWS:
        described = [p for p in listed if shows.get(p) or moved.get(images[p])]
        folders = defaultdict(lambda: [0, 0])
        for path in listed:
            folder = str(Path(path).parent)
            folders[folder][0] += 1
            folders[folder][1] += rows[path]["kb"]
        out += ["## Folders", "", f"Over {REGISTER_ROWS} images, so folders replace rows. Largest first.", "", "| Folder | Images | KB |", "| - | - | - |"]
        out += [f"| `{f}` | {c} | {kb} |" for f, (c, kb) in sorted(folders.items(), key=lambda kv: -kv[1][1])[:60]] + [""]
        listed = described
    if listed:
        out += ["## Repo images", "", "| Image | KB | Used by | Shows |", "| - | - | - | - |"]
        for path in listed:
            used = rows[path]["used"]
            who = " ".join(f"`{u}`" for u in used[:2]) + (f" +{len(used) - 2}" if len(used) > 2 else "")
            out.append(f"| `{path}` | {rows[path]['kb']} | {who} | {cell(shows.get(path) or moved.get(images[path], ''))} |")
    target.write_text("\n".join(out) + "\n")
    state["images"] = images
    save_state(map_dir, state)
    stamp(map_dir, files, [IMAGES_PAGE])
    print(f"wrote {target}")


def stamp(map_dir, files, names):
    state = load_state(map_dir)
    for name in names:
        page = map_dir / name
        if not page.exists():
            sys.exit(f"no such page: {name}")
        state["pages"][name] = covered(name, page.read_text(), files)
    save_state(map_dir, state)


def cmd_stamp(root, map_dir, args):
    """Record that these pages are true of the code as it stands now."""
    names = args.pages or [p.relative_to(map_dir).as_posix() for p in pages(map_dir)]
    names = [str(Path(n).resolve().relative_to(map_dir)) if (Path(n).exists() and Path(n).resolve().is_relative_to(map_dir)) else n for n in names]
    stamp(map_dir, tree(root, map_dir), names)
    print(f"stamped {len(names)} pages")


def lint(root, map_dir, files):
    errors, warnings = [], []
    link = re.compile(r"(!?)\[([^\]]*)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
    named_path = re.compile(r"`([\w@.-]+(?:/[\w@.+-]+)+\.\w+)(?::\d+(?:-\d+)?)?`")
    all_pages = pages(map_dir)
    graph, used = {}, set()
    for page in all_pages:
        name = page.relative_to(map_dir).as_posix()
        text = page.read_text()
        rows = text.splitlines()
        if len(rows) > PAGE_LIMIT:
            errors.append(f"{name}: {len(rows)} lines, over the limit of {PAGE_LIMIT}")
        elif len(rows) > PAGE_AIM:
            warnings.append(f"{name}: {len(rows)} lines, over the aim of {PAGE_AIM}")
        if name == "README.md" and len(rows) > ROOT_AIM:
            warnings.append(f"README.md: {len(rows)} lines, a root over {ROOT_AIM} is doing a page's job")
        if len(rows) > NEEDS_CONTENTS and "## Contents" not in text:
            errors.append(f"{name}: over {NEEDS_CONTENTS} lines without a ## Contents list")
        if name != "README.md" and not header(text, "Up").startswith("["):
            errors.append(f"{name}: no 'Up: [Parent](...)' trail in its first lines")
        if covers(text):
            matched = covered(name, text, files)
            code = code_files(files)
            if not matched:
                errors.append(f"{name}: Covers matches no files")
            elif len(code) >= 10 and sum(p in matched for p in code) > len(code) * COVERS_SHARE:
                warnings.append(f"{name}: Covers takes in over half the code, so it goes stale on most changes")
        graph[page.resolve()] = set()
        body = re.sub(r"```.*?```", "", text, flags=re.S)
        for is_image, alt, target in link.findall(re.sub(r"`[^`\n]*`", "", body)):
            if re.match(r"^[a-z]+:", target) or target.startswith("#"):
                continue
            resolved = (page.parent / target.split("#")[0]).resolve()
            if not resolved.exists():
                errors.append(f"{name}: broken link to {target}")
            elif resolved.suffix == ".md":
                graph[page.resolve()].add(resolved)
            else:
                used.add(resolved)
                if is_image and not alt.strip():
                    errors.append(f"{name}: image {target} has no alt text")
        if name not in (IMAGES_PAGE, DUPES_PAGE):
            for line in body.splitlines():
                if line.startswith("Covers:"):
                    continue
                for mention in named_path.findall(line):
                    if not (root / mention).exists() and not (map_dir / mention).exists() and not (page.parent / mention).exists():
                        warnings.append(f"{name}: names `{mention}`, which is gone")
    start = (map_dir / "README.md").resolve()
    if not start.exists():
        errors.append("README.md: the root page is missing")
    depth, queue = {start: 0}, deque([start])
    while queue:
        current = queue.popleft()
        for neighbour in graph.get(current, ()):
            if neighbour in graph and neighbour not in depth:
                depth[neighbour] = depth[current] + 1
                queue.append(neighbour)
    for page in all_pages:
        name, resolved = page.relative_to(map_dir).as_posix(), page.resolve()
        if resolved not in depth:
            errors.append(f"{name}: not reachable from README.md")
        elif depth[resolved] > MAX_DEPTH:
            warnings.append(f"{name}: {depth[resolved]} links from the root, over {MAX_DEPTH}")
    for image in sorted(p for p in map_dir.rglob("*") if suffix(p.name) in IMAGES):
        name = image.relative_to(map_dir).as_posix()
        if not name.startswith("images/"):
            errors.append(f"{name}: images belong in map/images/")
        if image.resolve() not in used:
            errors.append(f"{name}: not linked from any page (run `images --write`, or delete it)")
        if image.stat().st_size > IMAGE_KB * 1000:
            warnings.append(f"{name}: {image.stat().st_size // 1000} KB, over {IMAGE_KB} KB for a reference")
    return errors, warnings


def cmd_check(root, map_dir, args):
    if not map_dir.exists():
        sys.exit("no map yet")
    files = tree(root, map_dir)
    errors, warnings = lint(root, map_dir, files)
    stale = stale_pages(map_dir, files, load_state(map_dir))
    mapped = set()
    for page in pages(map_dir):
        name = page.relative_to(map_dir).as_posix()
        if name not in (IMAGES_PAGE, DUPES_PAGE):
            mapped |= set(covered(name, page.read_text(), files))
    loose = Counter(p.split("/")[0] for p in code_files(files) if p not in mapped)
    for line in warnings:
        print(f"warning: {line}")
    for line in errors:
        print(f"error: {line}")
    for name, changes in sorted(stale.items()):
        print(f"stale: {name}: " + ", ".join(changes[:5]) + (f", +{len(changes) - 5} more" if len(changes) > 5 else ""))
    if loose:
        print("not covered by a page (fine unless an area needs one): " + ", ".join(f"{d} ({c})" for d, c in loose.most_common(8)))
    print(f"{len(pages(map_dir))} pages: {len(errors)} errors, {len(warnings)} warnings, {len(stale)} stale")
    sys.exit(1 if errors or stale else 0)


def cmd_status(root, map_dir, args):
    """One line when the map is behind, nothing otherwise. Read-only, for session-start hooks."""
    if not map_dir.exists():
        return
    stale = stale_pages(map_dir, tree(root, map_dir), load_state(map_dir))
    if stale:
        names = ", ".join(sorted(stale)[:4]) + (f" +{len(stale) - 4}" if len(stale) > 4 else "")
        print(f"Project map: {len(stale)} page(s) out of date ({names}). Treat them with suspicion, and refresh with the map skill when you next rely on them.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("init", help="create map/ and git-ignore it; refuses a map/ it did not make")
    commands.add_parser("status", help="one line if stale, otherwise silent")
    commands.add_parser("check", help="lint pages and list stale ones; exits 1 if any")
    scan = commands.add_parser("scan", help="code by area")
    scan.add_argument("--limit", type=int, default=25)
    symbols = commands.add_parser("symbols", help="exported names ranked by fan-in")
    symbols.add_argument("glob", nargs="?")
    symbols.add_argument("--limit", type=int, default=60)
    for name, text in (("dupes", "repeated code, same-named exports, identical files"), ("images", "image inventory, exact copies, unreferenced")):
        command = commands.add_parser(name, help=text)
        command.add_argument("--write", action="store_true", help=f"regenerate map/{name}.md, keeping its last column")
        command.add_argument("--limit", type=int, default=15)
    stamp_parser = commands.add_parser("stamp", help="mark pages as true of the code now; all pages if none named")
    stamp_parser.add_argument("pages", nargs="*")
    args = parser.parse_args()
    root, map_dir = locate()
    globals()["cmd_" + args.command](root, map_dir, args)


if __name__ == "__main__":
    main()
